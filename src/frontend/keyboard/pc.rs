use winit::keyboard::KeyCode;

/// Returns the make code for KeyCode, used for ROM mode when a guest BIOS
/// is maintaining modifier keys.
pub(crate) fn winit_to_pc_scan_code(key: KeyCode) -> Option<u8> {
    let scan_code = match key {
        KeyCode::KeyA => 0x1E,
        KeyCode::KeyB => 0x30,
        KeyCode::KeyC => 0x2E,
        KeyCode::KeyD => 0x20,
        KeyCode::KeyE => 0x12,
        KeyCode::KeyF => 0x21,
        KeyCode::KeyG => 0x22,
        KeyCode::KeyH => 0x23,
        KeyCode::KeyI => 0x17,
        KeyCode::KeyJ => 0x24,
        KeyCode::KeyK => 0x25,
        KeyCode::KeyL => 0x26,
        KeyCode::KeyM => 0x32,
        KeyCode::KeyN => 0x31,
        KeyCode::KeyO => 0x18,
        KeyCode::KeyP => 0x19,
        KeyCode::KeyQ => 0x10,
        KeyCode::KeyR => 0x13,
        KeyCode::KeyS => 0x1F,
        KeyCode::KeyT => 0x14,
        KeyCode::KeyU => 0x16,
        KeyCode::KeyV => 0x2F,
        KeyCode::KeyW => 0x11,
        KeyCode::KeyX => 0x2D,
        KeyCode::KeyY => 0x15,
        KeyCode::KeyZ => 0x2C,
        KeyCode::Digit1 => 0x02,
        KeyCode::Digit2 => 0x03,
        KeyCode::Digit3 => 0x04,
        KeyCode::Digit4 => 0x05,
        KeyCode::Digit5 => 0x06,
        KeyCode::Digit6 => 0x07,
        KeyCode::Digit7 => 0x08,
        KeyCode::Digit8 => 0x09,
        KeyCode::Digit9 => 0x0A,
        KeyCode::Digit0 => 0x0B,
        KeyCode::Minus => 0x0C,
        KeyCode::Equal => 0x0D,
        KeyCode::Enter => 0x1C,
        KeyCode::Backspace => 0x0E,
        KeyCode::Space => 0x39,
        KeyCode::Escape => 0x01,
        KeyCode::Tab => 0x0F,
        KeyCode::Slash => 0x35,
        KeyCode::Quote => 0x28,
        KeyCode::Backquote => 0x29,
        KeyCode::Backslash => 0x2B,
        KeyCode::BracketLeft => 0x1A,
        KeyCode::BracketRight => 0x1B,
        KeyCode::Semicolon => 0x27,
        KeyCode::Comma => 0x33,
        KeyCode::Period => 0x34,
        KeyCode::F1 => 0x3B,
        KeyCode::F2 => 0x3C,
        KeyCode::F3 => 0x3D,
        KeyCode::F4 => 0x3E,
        KeyCode::F5 => 0x3F,
        KeyCode::F6 => 0x40,
        KeyCode::F7 => 0x41,
        KeyCode::F8 => 0x42,
        KeyCode::F9 => 0x43,
        KeyCode::F10 => 0x44,
        KeyCode::ShiftLeft => 0x2A,
        KeyCode::ShiftRight => 0x36,
        KeyCode::ControlLeft => 0x1D,
        KeyCode::ControlRight => 0x1D, // Alias
        KeyCode::AltLeft => 0x38,
        KeyCode::AltRight => 0x38, // Alias
        KeyCode::CapsLock => 0x3A,
        KeyCode::NumLock => 0x45,
        KeyCode::ScrollLock => 0x46,
        KeyCode::Numpad7 => 0x47,
        KeyCode::Numpad8 => 0x48,
        KeyCode::Numpad9 => 0x49,
        KeyCode::NumpadSubtract => 0x4A,
        KeyCode::Numpad4 => 0x4B,
        KeyCode::Numpad5 => 0x4C,
        KeyCode::Numpad6 => 0x4D,
        KeyCode::NumpadAdd => 0x4E,
        KeyCode::Numpad1 => 0x4F,
        KeyCode::Numpad2 => 0x50,
        KeyCode::Numpad3 => 0x51,
        KeyCode::Numpad0 => 0x52,
        KeyCode::NumpadDecimal => 0x53,
        KeyCode::NumpadMultiply => 0x37,
        KeyCode::ArrowUp => 0x48,    // Numpad up
        KeyCode::ArrowDown => 0x50,  // Numpad down
        KeyCode::ArrowLeft => 0x4B,  // Numpad left
        KeyCode::ArrowRight => 0x4D, // Numpad right
        KeyCode::PageUp => 0x49,     // Numpad page up
        KeyCode::PageDown => 0x51,   // Numpad page down
        KeyCode::Home => 0x47,       // Numpad home
        KeyCode::End => 0x4F,        // Numpad end
        KeyCode::Insert => 0x52,     // Numpad insert
        KeyCode::Delete => 0x53,     // Numpad delete
        _ => return None,
    };
    Some(scan_code as u8)
}
